ALTER TABLE public.simulados
  ADD COLUMN IF NOT EXISTS data_realizacao DATE;

CREATE TABLE IF NOT EXISTS public.presencas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id BIGINT NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  simulado_id BIGINT NOT NULL REFERENCES public.simulados(id) ON DELETE CASCADE,
  presente BOOLEAN NOT NULL DEFAULT FALSE,
  observacao TEXT,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (aluno_id, simulado_id)
);

CREATE INDEX IF NOT EXISTS idx_presencas_aluno ON public.presencas(aluno_id);
CREATE INDEX IF NOT EXISTS idx_presencas_simulado ON public.presencas(simulado_id);

