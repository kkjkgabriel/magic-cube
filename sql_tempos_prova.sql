CREATE TABLE IF NOT EXISTS public.tempos_prova (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id bigint NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  simulado text NOT NULL,
  dia text NOT NULL CHECK (dia IN ('Dia 1','Dia 2')),
  tempo_minutos integer NOT NULL CHECK (tempo_minutos > 0),
  origem text NOT NULL DEFAULT 'planilha histórica',
  UNIQUE (aluno_id, simulado, dia)
);
ALTER TABLE public.tempos_prova ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Leitura tempos prova" ON public.tempos_prova;
CREATE POLICY "Leitura tempos prova" ON public.tempos_prova FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "Escrita tempos prova" ON public.tempos_prova;
CREATE POLICY "Escrita tempos prova" ON public.tempos_prova FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

