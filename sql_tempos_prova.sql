-- Verifique quantos tempos foram importados:
SELECT s.codigo, t.dia, count(*) AS alunos_com_tempo,
       round(avg(t.tempo_minutos)) AS media_minutos
FROM public.tempos_prova t JOIN public.simulados s ON s.codigo=t.simulado
GROUP BY s.codigo,t.dia ORDER BY s.codigo,t.dia;
