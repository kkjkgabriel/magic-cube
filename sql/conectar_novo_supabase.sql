-- Datas dos simulados
ALTER TABLE public.simulados
  ADD COLUMN IF NOT EXISTS data_dia1 DATE,
  ADD COLUMN IF NOT EXISTS data_dia2 DATE;

-- IDs automáticos para novos registros (os IDs antigos são preservados)
CREATE SEQUENCE IF NOT EXISTS public.alunos_id_seq;
SELECT setval('public.alunos_id_seq', COALESCE((SELECT MAX(id) FROM public.alunos), 0) + 1, false);
ALTER TABLE public.alunos ALTER COLUMN id SET DEFAULT nextval('public.alunos_id_seq');
ALTER SEQUENCE public.alunos_id_seq OWNED BY public.alunos.id;

CREATE SEQUENCE IF NOT EXISTS public.simulados_id_seq;
SELECT setval('public.simulados_id_seq', COALESCE((SELECT MAX(id) FROM public.simulados), 0) + 1, false);
ALTER TABLE public.simulados ALTER COLUMN id SET DEFAULT nextval('public.simulados_id_seq');
ALTER SEQUENCE public.simulados_id_seq OWNED BY public.simulados.id;

CREATE SEQUENCE IF NOT EXISTS public.questoes_id_seq;
SELECT setval('public.questoes_id_seq', COALESCE((SELECT MAX(id) FROM public.questoes), 0) + 1, false);
ALTER TABLE public.questoes ALTER COLUMN id SET DEFAULT nextval('public.questoes_id_seq');
ALTER SEQUENCE public.questoes_id_seq OWNED BY public.questoes.id;

-- Tabela de frequência
CREATE TABLE IF NOT EXISTS public.frequencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id BIGINT NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  data_aula DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Presente','Ausente','Justificado')),
  observacao TEXT,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (aluno_id, data_aula)
);
CREATE INDEX IF NOT EXISTS idx_frequencias_data ON public.frequencias(data_aula);
CREATE INDEX IF NOT EXISTS idx_frequencias_aluno ON public.frequencias(aluno_id);

-- RLS
ALTER TABLE public.alunos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.simulados ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.questoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.respostas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.frequencias ENABLE ROW LEVEL SECURITY;

-- Leitura pública
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['alunos','simulados','questoes','respostas','frequencias'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS "public_read_%s" ON public.%I', t, t);
    EXECUTE format('CREATE POLICY "public_read_%s" ON public.%I FOR SELECT TO anon USING (true)', t, t);
  END LOOP;
END $$;

-- Escrita pública necessária para o sistema sem login
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['alunos','simulados','questoes','respostas','frequencias'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS "public_insert_%s" ON public.%I', t, t);
    EXECUTE format('DROP POLICY IF EXISTS "public_update_%s" ON public.%I', t, t);
    EXECUTE format('DROP POLICY IF EXISTS "public_delete_%s" ON public.%I', t, t);
    EXECUTE format('CREATE POLICY "public_insert_%s" ON public.%I FOR INSERT TO anon WITH CHECK (true)', t, t);
    EXECUTE format('CREATE POLICY "public_update_%s" ON public.%I FOR UPDATE TO anon USING (true) WITH CHECK (true)', t, t);
    EXECUTE format('CREATE POLICY "public_delete_%s" ON public.%I FOR DELETE TO anon USING (true)', t, t);
  END LOOP;
END $$;
