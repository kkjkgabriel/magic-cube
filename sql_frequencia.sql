CREATE TABLE IF NOT EXISTS public.frequencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  aluno_id BIGINT NOT NULL REFERENCES public.alunos(id) ON DELETE CASCADE,
  data_aula DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Presente','Ausente','Justificado')),
  observacao TEXT,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (aluno_id, data_aula)
);

CREATE INDEX IF NOT EXISTS idx_frequencias_data ON public.frequencias(data_aula);
CREATE INDEX IF NOT EXISTS idx_frequencias_aluno ON public.frequencias(aluno_id);

ALTER TABLE public.frequencias ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_frequencias" ON public.frequencias;
CREATE POLICY "public_read_frequencias"
ON public.frequencias FOR SELECT TO anon USING (true);

DROP POLICY IF EXISTS "public_insert_frequencias" ON public.frequencias;
CREATE POLICY "public_insert_frequencias"
ON public.frequencias FOR INSERT TO anon WITH CHECK (true);

DROP POLICY IF EXISTS "public_update_frequencias" ON public.frequencias;
CREATE POLICY "public_update_frequencias"
ON public.frequencias FOR UPDATE TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "public_delete_frequencias" ON public.frequencias;
CREATE POLICY "public_delete_frequencias"
ON public.frequencias FOR DELETE TO anon USING (true);
